/**
 * The style registry.
 *
 * A style is not a mode with its own code path, it is a painter (or a
 * whole-frame process) plus a short list of facts about what it needs. The
 * panel reads those facts to decide which controls to show, the renderer reads
 * them to decide how to cut the grid, and the exporter reads `glyph` to decide
 * whether text output is even meaningful. Everything asking one table means a
 * new style is a row here and a function in `painters.ts` or `process.ts`, and
 * nothing else in the app has to learn about it.
 *
 * `group` is behaviour (how the renderer treats it) and `family` is where it
 * sits in the picker. They are kept apart on purpose: Low poly behaves like a
 * tile and reads as geometry, Thermal is a process and reads as light.
 */

