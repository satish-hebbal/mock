export type StyleGroup = 'glyph' | 'shape' | 'raster' | 'process'

/** Where a style sits in the picker. */
export type StyleFamily = 'type' | 'marks' | 'tiles' | 'print' | 'paint' | 'light'

export interface StyleSpec {
  id: AsciiStyleId
  label: string
  group: StyleGroup
  family: StyleFamily
  /**
   * The glyph on the style's button, where a button is drawn rather than a
   * thumbnail. Chosen to depict what the painter actually draws rather than to
   * label the category.
   */
  icon: LucideIcon
  /** draws characters from a ramp, so .txt, ANSI, HTML and SVG all work */
  glyph: boolean
  /** forces square cells: a LEGO brick with a 1.8 aspect is not a LEGO brick */
  square: boolean
  /** honours the grout slider */
  gap: boolean
  /** reads the character ramp, so the character set picker applies */
  ramp?: boolean
  /** one line, shown under the pointer and in the section's info dot */
  hint: string
  /** settings beyond the shared grid and tone */
  params?: ParamSpec[]
  /** a starting cell size, for styles that are unreadable at the text default */
  cell?: number
}

